/**
 * Executes an AI generation request using Cloudflare AI, OpenAI, or Fallback.
 * @param {Object} options
 * @param {string} options.assistant - 'booking' | 'stock' | 'real_estate' | 'dev_tutor' | 'general'
 * @param {string} options.prompt - User message / question
 * @param {Array} [options.messages] - Conversation history array [{role, content}]
 * @param {Object} options.env - Cloudflare Workers environment bindings (env.AI, env.OPENAI_API_KEY)
 * @param {string} [options.customSystemPrompt] - Optional override for system prompt
 * @returns {Promise<{ text: string, provider: string, model: string, disclaimer?: string }>}
 */
export async function executeAI({ assistant = 'general', prompt, messages = [], env = {}, customSystemPrompt }) {
  const systemPrompt = customSystemPrompt || SYSTEM_PROMPTS[assistant] || SYSTEM_PROMPTS.booking;

  const conversation = [];
  conversation.push({ role: 'system', content: systemPrompt });

  if (messages && Array.isArray(messages) && messages.length > 0) {
    for (const m of messages) {
      if (m.role && m.content) {
        conversation.push({ role: m.role, content: m.content });
      } else if (m.message) {
        conversation.push({ role: m.sender_id === 9999 ? 'assistant' : 'user', content: m.message });
      }
    }
  }

  if (prompt && (!messages.length || conversation[conversation.length - 1].content !== prompt)) {
    conversation.push({ role: 'user', content: prompt });
  }

  // 1. Try Cloudflare Workers AI binding if present
  if (env.AI && typeof env.AI.run === 'function') {
    try {
      const model = '@cf/meta/llama-3.1-8b-instruct';
      const result = await env.AI.run(model, {
        messages: conversation,
        max_tokens: 1024,
        temperature: 0.6
      });

      const reply = result?.response || result?.text || (typeof result === 'string' ? result : null);
      if (reply) {
        return {
          text: formatOutput(reply, assistant),
          provider: 'cloudflare-ai',
          model
        };
      }
    } catch (cfError) {
      console.warn('[Cloudflare AI] Failed, falling back...', cfError.message);
    }
  }

  // 2. Try OpenAI API if OPENAI_API_KEY is configured
  const apiKey = env.OPENAI_API_KEY || (typeof process !== 'undefined' ? process.env?.OPENAI_API_KEY : null);
  if (apiKey) {
    try {
      const res = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${apiKey}`
        },
        body: JSON.stringify({
          model: 'gpt-4o-mini',
          messages: conversation,
          temperature: 0.7,
          max_tokens: 1024
        })
      });

      if (res.ok) {
        const data = await res.json();
        const content = data.choices?.[0]?.message?.content;
        if (content) {
          return {
            text: formatOutput(content, assistant),
            provider: 'openai',
            model: data.model || 'gpt-4o-mini'
          };
        }
      }
    } catch (oaiError) {
      console.warn('[OpenAI API] Failed, falling back...', oaiError.message);
    }
  }

  // 3. Smart Domain Fallback Engine
  const fallbackReply = generateDomainFallback(assistant, prompt || (messages[messages.length - 1]?.content || ''));
  return {
    text: formatOutput(fallbackReply, assistant),
    provider: 'fawaz-smart-ai-engine',
    model: 'fawaz-domain-v2'
  };
}

function formatOutput(text, assistant) {
  if (assistant === 'stock' && !text.includes('DISCLAIMER') && !text.includes('تنويه')) {
    return `${text}\n\n> ⚠️ **DISCLAIMER**: *This quantitative analysis and prediction is AI-generated for educational/informational screening purposes only and is strictly non-financial advice. Always conduct your own research before trading.*`;
  }
  return text;
}

